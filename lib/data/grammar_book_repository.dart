  static GrammarBookCopy copy(String locale) =>
      _copies[locale] ?? _copies['en']!;

  static String localizedTopicTitle(
    String locale,
    int index,
    String fallback,
  ) {
    final titles = _topicTitles[locale];
    if (titles != null && index >= 0 && index < titles.length) {
      return titles[index];
    }
    if (locale == 'en') return fallback;
    return '${copy(locale).chapter} ${index + 1}';
  }

  static String profileFor(String locale, LanguageOption language) {
    final copy = GrammarBookRepository.copy(locale);
    final signature = _signatures[language.code] ??
        const [
          'context',
          'word_order',
          'sound_script',
        ];
    final featureNames = _featureNames[locale] ?? _featureNames['en']!;
    final features =
        signature.map((key) => featureNames[key] ?? key).join(' · ');
    return copy.profileBody
        .replaceAll('{language}', language.nativeName)
        .replaceAll('{features}', features);
  }

  static List<String> explanationFor(
    String locale, {
    required String topic,
    required String language,
    required String level,
  }) =>
      copy(locale)
          .explanationParagraphs
          .map(
            (line) => line
                .replaceAll('{topic}', topic)
                .replaceAll('{language}', language)
                .replaceAll('{level}', level),
          )
          .toList();

